#!/usr/bin/env python3
"""Corrections registry tooling (registry: cloud-kit/hooks/corrections.json).

  python3 scripts/corrections.py inventory [--memory-dir DIR] [--check]
      Write docs/learning/corrections-inventory.md: every correction, its class (check / eval /
      prose), where it lives and how it is enforced. With --memory-dir, feedback-*.md memories not
      yet cited as a source are listed as UNCLASSIFIED. --check fails if the committed file is stale.
  python3 scripts/corrections.py unenforced [--check]
      Write docs/learning/unenforced.md: corrections still prose-only, and evals not yet written.
  python3 scripts/corrections.py prune [--hits FILE] [--days N] [--memory-dir DIR]
      Print the monthly prune report: checks that never fired, stale dated facts in the
      always-loaded rules, word budget status, unclassified feedback memories.
  python3 scripts/corrections.py words
      Print the always-loaded word count and the budget.

Standard library only. Makes no network calls.
"""
import argparse, glob, json, os, re, sys, time
from datetime import date, datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REGISTRY = os.path.join(ROOT, "cloud-kit", "hooks", "corrections.json")
INVENTORY = os.path.join(ROOT, "docs", "learning", "corrections-inventory.md")
UNENFORCED = os.path.join(ROOT, "docs", "learning", "unenforced.md")
BUDGET = os.path.join(ROOT, "docs", "learning", "budget.json")
MAC_MEMORY = os.path.expanduser("~/.claude/projects/-Users-elliotkelly-Developer/memory")


def load():
    with open(REGISTRY) as f:
        return json.load(f)["corrections"]


def always_loaded_files():
    with open(BUDGET) as f:
        b = json.load(f)
    files = []
    for pattern in b["files"]:
        files += sorted(glob.glob(os.path.join(ROOT, pattern)))
    return b, files


def word_count():
    b, files = always_loaded_files()
    per = {os.path.relpath(f, ROOT): len(open(f).read().split()) for f in files}
    return b, per, sum(per.values())


def enforcement(e):
    if e["class"] == "check":
        c = e["check"]
        if c.startswith("external:"):
            return c[len("external:"):]
        return f"`{e['id']}` ({', '.join(e['surface'] if isinstance(e['surface'], list) else [e['surface']])} → {e['action']})"
    if e["class"] == "eval":
        exists = os.path.exists(os.path.join(ROOT, e["eval"], "prompt.md"))
        return f"`{e['eval']}`" + ("" if exists else " (NOT WRITTEN)")
    return "prose"


def unclassified_memories(entries, memory_dir):
    if not memory_dir or not os.path.isdir(memory_dir):
        return None
    cited = " ".join(e.get("source", "") for e in entries)
    return [os.path.basename(p) for p in sorted(glob.glob(os.path.join(memory_dir, "feedback-*.md")))
            if os.path.basename(p)[:-3] not in cited]


def render_inventory(entries, memory_dir=None):
    counts = {k: sum(1 for e in entries if e["class"] == k) for k in ("check", "eval", "prose")}
    _, per, total = word_count()
    out = [
        "# Corrections inventory",
        "",
        "Generated by `python3 scripts/corrections.py inventory` from `cloud-kit/hooks/corrections.json`. Do not edit by hand:",
        "add or change a correction with `/learnings` (it edits the registry, then regenerates this file).",
        "",
        "Every founder correction from the always-loaded rules and the High-Level output style is one row, classified as:",
        "",
        "- **check**: mechanical, enforced by `cloud-kit/hooks/correction-checks.py` (or the named hook/test). Unit-tested on a bad and a good example.",
        "- **eval**: behaviour a regex can't judge; a `claude plugin eval` case under `evals/`.",
        "- **prose**: judgement; stays as a rule line. The *Home* column is the one place it lives.",
        "",
        f"Totals: {len(entries)} corrections; {counts['check']} checks, {counts['eval']} evals, {counts['prose']} prose. "
        f"Always-loaded words: {total}.",
        "",
        "| ID | Rule | Class | Enforced by | Home | Source |",
        "|---|---|---|---|---|---|",
    ]
    order = {"check": 0, "eval": 1, "prose": 2}
    for e in sorted(entries, key=lambda e: (order[e["class"]], e["home"], e["id"])):
        rule = e["rule"].replace("|", "\\|")
        out.append(f"| `{e['id']}` | {rule} | {e['class']} | {enforcement(e).replace('|', '/')} | `{e['home']}` | {e.get('source', '').replace('|', '/')} |")
    out += ["", "## Not in this repo", "",
            "- **Feedback memories** (`feedback-*.md`, Mac only) and **Mac-only rule files** are outside the repo, so a cloud run "
            "can't read them. The monthly prune runs `inventory --memory-dir` on the Mac to list any not yet cited as a source "
            "here; each gets classified with `/learnings`.",
            "- Retired rule files are listed in `cloud-kit/RETIRED`; `cloud-kit/install.sh` moves them out of `~/.claude/rules`."]
    un = unclassified_memories(entries, memory_dir)
    if un is not None:
        out += ["", f"## Unclassified feedback memories ({len(un)})", ""] + [f"- `{n}`" for n in un] + ([] if un else ["- none"])
    return "\n".join(out) + "\n"


def render_unenforced(entries):
    prose = [e for e in entries if e["class"] == "prose"]
    missing = [e for e in entries if e["class"] == "eval" and not os.path.exists(os.path.join(ROOT, e["eval"], "prompt.md"))]
    out = ["# Corrections not yet enforced", "",
           "Generated by `python3 scripts/corrections.py unenforced`. These corrections rely on Claude reading a rule. "
           "Each monthly prune, pick any that have been broken since and promote them to a check or eval with `/learnings`.", "",
           f"## Evals named but not written ({len(missing)})", ""]
    out += [f"- `{e['id']}`: {e['rule']} → `{e['eval']}`" for e in missing] or ["- none"]
    out += ["", f"## Prose only ({len(prose)})", ""]
    for home in sorted({e["home"] for e in prose}):
        out.append(f"### `{home}`")
        out += [f"- `{e['id']}`: {e['rule']}" for e in prose if e["home"] == home]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def write_or_check(path, text, check):
    if check:
        current = open(path).read() if os.path.exists(path) else ""
        if current != text:
            print(f"FAIL: {os.path.relpath(path, ROOT)} is stale; run scripts/corrections.py")
            return 1
        print(f"OK: {os.path.relpath(path, ROOT)} up to date")
        return 0
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


DATE = re.compile(r"\b(20\d\d-\d\d-\d\d)\b")


def stale_facts(days):
    """Lines in the always-loaded files whose newest date is older than `days` and that state a measurement."""
    _, files = always_loaded_files()
    today = date.today()
    out = []
    for f in files:
        for n, line in enumerate(open(f), 1):
            dates = DATE.findall(line)
            if not dates:
                continue
            newest = max(datetime.strptime(d, "%Y-%m-%d").date() for d in dates)
            if (today - newest).days > days and re.search(r"\d+\s*(?:%|GB|MB|k\b|words|jobs|tests|s\b|h\b|\$)|measured|checked|verified|left|remaining", line, re.I):
                out.append(f"{os.path.relpath(f, ROOT)}:{n} ({newest}): {line.strip()[:120]}")
    return out


def prune(args):
    entries = load()
    checks = [e for e in entries if e["class"] == "check" and not e["check"].startswith("external:")]
    fired, since = {}, None
    if os.path.exists(args.hits):
        cutoff = time.time() - args.days * 86400
        for line in open(args.hits):
            try:
                row = json.loads(line)
            except Exception:
                continue
            if row.get("ts", 0) >= cutoff:
                fired[row["id"]] = fired.get(row["id"], 0) + 1
                since = min(since or row["ts"], row["ts"])
    b, per, total = word_count()
    print(f"# Monthly prune report ({date.today()})\n")
    print(f"## Checks by hits in the last {args.days} days")
    if not os.path.exists(args.hits):
        print(f"- no hits log at {args.hits}: run this on the machine that runs the hooks")
    for e in sorted(checks, key=lambda e: -fired.get(e["id"], 0)):
        n = fired.get(e["id"], 0)
        print(f"- `{e['id']}`: {n}" + ("  ← never fired: keep (rare but costly?) or retire" if n == 0 else ""))
    print(f"\n## Stale dated facts (older than {args.stale_days} days) in always-loaded files")
    for s in stale_facts(args.stale_days) or ["none"]:
        print(f"- {s}")
    print(f"\n## Word budget\n- always-loaded: {total} / budget {b['budget']} ({'OK' if total <= b['budget'] else 'OVER'})")
    for k, v in sorted(per.items(), key=lambda kv: -kv[1]):
        print(f"  - {k}: {v}")
    un = unclassified_memories(entries, args.memory_dir)
    print("\n## Unclassified feedback memories")
    if un is None:
        print(f"- memory dir not found ({args.memory_dir}): run on the Mac")
    else:
        for n in un or ["none"]:
            print(f"- {n}")
    missing = [e for e in entries if e["class"] == "eval" and not os.path.exists(os.path.join(ROOT, e["eval"], "prompt.md"))]
    print("\n## Evals named but not written")
    for e in missing or [None]:
        print(f"- {e['id']} → {e['eval']}" if e else "- none")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    i = sub.add_parser("inventory")
    i.add_argument("--memory-dir")
    i.add_argument("--check", action="store_true")
    u = sub.add_parser("unenforced")
    u.add_argument("--check", action="store_true")
    p = sub.add_parser("prune")
    p.add_argument("--hits", default=os.path.expanduser("~/.claude/state/corrections-hits.jsonl"))
    p.add_argument("--days", type=int, default=30)
    p.add_argument("--stale-days", type=int, default=45)
    p.add_argument("--memory-dir", default=MAC_MEMORY)
    sub.add_parser("words")
    a = ap.parse_args(argv)
    if a.cmd == "inventory":
        return write_or_check(INVENTORY, render_inventory(load(), a.memory_dir), a.check)
    if a.cmd == "unenforced":
        return write_or_check(UNENFORCED, render_unenforced(load()), a.check)
    if a.cmd == "prune":
        return prune(a)
    b, per, total = word_count()
    print(f"{total} / {b['budget']}")
    return 0 if total <= b["budget"] else 1


if __name__ == "__main__":
    sys.exit(main())
